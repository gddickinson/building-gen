"""FastAPI web app for building-gen: serves the front end in static/ and the JSON API under /api.

Run with `python run_web.py` (http://127.0.0.1:8228, local only). `scripts/build_static.py` exports every path in
STATIC_ENDPOINTS to JSON for the GitHub Pages site, so keep that list in step with the GET routes below. On the
static site the generator itself runs in the browser (static/bg_*.js); /building and /glb need this server.
"""
import sys
from pathlib import Path

from fastapi import FastAPI, HTTPException, Request
from fastapi.responses import FileResponse, Response
from fastapi.staticfiles import StaticFiles

STATIC = Path(__file__).resolve().parent / "static"
ROOT = Path(__file__).resolve().parents[3]
DOC_IMAGES = ROOT / "docs" / "images"
# Images of the detailed (engineering) model shown on the Detail page; copied into the static site by build_static.
DETAIL_IMAGES = ["front_elevation.png", "cross_section.png", "building_systems.png"]

if str(ROOT / "src") not in sys.path:  # run from a checkout without `pip install -e .`
    sys.path.insert(0, str(ROOT / "src"))

from buildgen.web import service  # noqa: E402

app = FastAPI(title="building-gen")
app.mount("/static/img", StaticFiles(directory=DOC_IMAGES), name="img")
app.mount("/static", StaticFiles(directory=STATIC), name="static")


@app.get("/", include_in_schema=False)
def index():
    return FileResponse(STATIC / "index.html")


@app.get("/api/info")
def info():
    """Project summary and real counts for the home page."""
    import yaml
    with open(service.TEMPLATE_DIR / "building_type_rules.yaml") as f:
        rules = yaml.safe_load(f)
    return {"title": "building-gen", "types": len(service.building_types()), "styles": 1,
            "style_controls": len(service.STYLE_CONTROLS), "researched_types": len(rules),
            "reference_cases": len(service.reference_cases())}


@app.get("/api/types")
def types():
    """Every building type: layout kind and the notes at the top of its template."""
    return [service.template_info(t) for t in service.building_types()]


@app.get("/api/templates")
def templates():
    """The YAML templates as JSON: the input of the in-browser generator."""
    return service.templates()


@app.get("/api/styles")
def styles():
    """Available styles, the georgian StyleParams and the parameters the web interface can change."""
    from dataclasses import asdict
    lib = service._pipeline.style_library
    controls = {k: (v if isinstance(v, list) else {"min": v[0], "max": v[1]}) for k, v in service.STYLE_CONTROLS.items()}
    return {"styles": lib.available_styles(), "params": {s: asdict(lib.get(s)) for s in lib.available_styles()},
            "controls": controls}


@app.get("/api/verify")
def verify():
    """Reference buildings from the Python generator (counts and .glb SHA-256) for the browser cross-check."""
    out = []
    for t, s, ov in service.reference_cases():
        r = service.generate(t, s, ov)
        d = service.describe(r)
        out.append({"type": t, "seed": s, "overrides": ov, "vertices": d["vertices"], "faces": d["faces"],
                    "nodes": len(d["nodes"]), "rooms": sum(len(p["rooms"]) for p in d["plans"]),
                    "glb_sha256": service.glb_sha256(r), "glb_length": len(service.glb_bytes(r))})
    return out


def _params(request: Request):
    q = dict(request.query_params)
    try:
        btype = q.pop("type", "townhouse")
        seed = int(q.pop("seed", 42))
        style = q.pop("style", "georgian")
        if btype not in service.building_types():
            raise ValueError(f"unknown building type '{btype}'")
        return btype, seed, service.clean_overrides(q), style
    except ValueError as e:
        raise HTTPException(400, str(e))


@app.get("/api/building")
def building(request: Request):
    """One building generated by Python: plans, stats, per-node mesh sizes and the .glb SHA-256."""
    btype, seed, ov, style = _params(request)
    try:
        r = service.generate(btype, seed, ov, style)
    except ValueError as e:
        raise HTTPException(400, str(e))
    d = service.describe(r)
    d["overrides"] = ov
    d["glb_sha256"] = service.glb_sha256(r)
    d["glb_length"] = len(service.glb_bytes(r))
    return d


@app.get("/api/glb")
def glb(request: Request):
    """The .glb file the Python package writes for these parameters."""
    btype, seed, ov, style = _params(request)
    r = service.generate(btype, seed, ov, style)
    name = f"{btype}_{style}_s{seed}.glb"
    return Response(service.glb_bytes(r), media_type="model/gltf-binary",
                    headers={"Content-Disposition": f'attachment; filename="{name}"'})


# GET paths (without the /api prefix) written to the static site as api/<path>.json.
STATIC_ENDPOINTS = ["/info", "/types", "/templates", "/styles", "/verify"]
