"""Pure helpers behind the web API: generate a building with optional style overrides and describe it as JSON.

Used by app.py and scripts/make_building_fixture.py. Style overrides only change the 3D geometry (floor plans
do not depend on the style), so the building is generated by the normal Pipeline and, if overrides are given,
its geometry is rebuilt with the changed StyleParams.
"""
from __future__ import annotations

import hashlib
from dataclasses import fields, replace
from pathlib import Path

import yaml

from ..geometry import GeometryBuilder
from ..pipeline import Pipeline, PipelineResult
from ..program.generator import is_building_template

TEMPLATE_DIR = Path(__file__).resolve().parent.parent / "program" / "templates"

# StyleParams fields the web interface lets you change, with their allowed ranges (choices for strings).
STYLE_CONTROLS = {
    "roof_type": ["hip", "gable", "flat"],
    "roof_pitch": (0.1, 1.2),
    "roof_overhang": (0.0, 1.0),
    "floor_height": (2.2, 4.5),
    "slab_thickness": (0.1, 0.5),
    "stair_riser": (0.14, 0.24),
}

# Buildings the node tests and the Verify page compare between Python and the JS port: every type at three
# seeds, plus style overrides.
REFERENCE_SEEDS = [0, 7, 42]
REFERENCE_OVERRIDES = [
    ("cottage", 42, {"roof_type": "gable"}),
    ("townhouse", 3, {"roof_type": "flat", "floor_height": 2.8}),
    ("tavern", 5, {"roof_type": "gable", "roof_pitch": 0.9, "roof_overhang": 0.6}),
    ("victorian_terrace", 11, {"roof_pitch": 0.2, "stair_riser": 0.15, "slab_thickness": 0.3}),
]

_pipeline = Pipeline()


def reference_cases() -> list:
    """[(type, seed, overrides)] compared between Python and the JS port."""
    return [(t, s, {}) for t in building_types() for s in REFERENCE_SEEDS] + list(REFERENCE_OVERRIDES)


def building_types() -> list[str]:
    """Sorted building type names (templates with floors or a grid)."""
    return sorted(_pipeline.program_gen.available_types())


def templates() -> dict:
    """Every building template as parsed from its YAML file."""
    out = {}
    for name in building_types():
        with open(TEMPLATE_DIR / f"{name}.yaml") as f:
            out[name] = yaml.safe_load(f)
    return out


def template_info(name: str) -> dict:
    """Description of one template: its comment header and layout kind."""
    path = TEMPLATE_DIR / f"{name}.yaml"
    if not is_building_template(path):
        raise KeyError(name)
    header = []
    for line in path.read_text().splitlines():
        if not line.startswith("#"):
            break
        header.append(line.lstrip("#").strip())
    while header and not header[-1]:
        header.pop()
    with open(path) as f:
        tmpl = yaml.safe_load(f)
    return {"name": name, "layout": "grid" if tmpl.get("layout_type") == "grid" else "template (BSP)",
            "notes": "\n".join(header)}


def clean_overrides(overrides: dict) -> dict:
    """Validate style overrides against STYLE_CONTROLS; raises ValueError on a bad name or value."""
    out = {}
    names = {f.name for f in fields(_pipeline.style_library.get("georgian"))}
    for key, value in overrides.items():
        if key not in STYLE_CONTROLS or key not in names:
            raise ValueError(f"unknown style parameter '{key}'")
        spec = STYLE_CONTROLS[key]
        if isinstance(spec, list):
            if value not in spec:
                raise ValueError(f"{key} must be one of {spec}")
            out[key] = value
        else:
            v = float(value)
            if not spec[0] <= v <= spec[1]:
                raise ValueError(f"{key} must be between {spec[0]} and {spec[1]}")
            out[key] = v
    return out


def generate(building_type: str, seed: int, overrides: dict | None = None, style: str = "georgian") -> PipelineResult:
    """Pipeline.generate, then the geometry rebuilt with the style overrides (if any)."""
    result = _pipeline.generate(building_type, style, seed)
    overrides = clean_overrides(overrides or {})
    if overrides:
        params = replace(result.style, **overrides)
        building = GeometryBuilder().build(result.floor_plans, params)
        building.building_type, building.style, building.seed = building_type, style, seed
        result = PipelineResult(program=result.program, floor_plans=result.floor_plans, building=building, style=params)
    return result


def scene_nodes(result: PipelineResult) -> list:
    """[(node name, Trimesh)] in scene order."""
    scene = result.building.mesh
    return [(node, scene.geometry[scene.graph[node][1]]) for node in scene.graph.nodes_geometry]


def describe(result: PipelineResult) -> dict:
    """Floor plans, stats and per-node mesh sizes of a generated building (no vertex arrays)."""
    plans = []
    for fp in result.floor_plans:
        rooms = []
        for r in fp.rooms:
            rooms.append({
                "name": r.name, "type": r.room_type, "bounds": list(r.bounds),
                "openings": [{"type": o.opening_type.value, "position": list(o.position), "width": o.width}
                             for o in r.openings],
                "fixtures": [{"type": fx.fixture_type.value, "x": fx.x, "y": fx.y, "width": fx.width,
                              "depth": fx.depth, "rotation": fx.rotation} for fx in getattr(r, "_fixtures", [])],
            })
        walls = [{"start": list(w.start), "end": list(w.end), "type": w.wall_type.value, "thickness": w.thickness}
                 for w in fp.walls]
        plans.append({"floor": fp.floor_index, "footprint": list(fp.footprint.bounds), "rooms": rooms, "walls": walls})
    nodes = [{"name": n, "vertices": len(m.vertices), "faces": len(m.faces),
              "sum": [float(x) for x in m.vertices.sum(axis=0)]} for n, m in scene_nodes(result)]
    b = result.building
    return {"type": b.building_type, "seed": b.seed, "style": b.style, "num_floors": b.num_floors,
            "footprint_area": b.footprint_area, "total_floor_area": b.total_floor_area, "plans": plans,
            "nodes": nodes, "vertices": sum(n["vertices"] for n in nodes), "faces": sum(n["faces"] for n in nodes)}


def glb_bytes(result: PipelineResult) -> bytes:
    """The .glb the CLI writes (Building3D.export)."""
    return result.building.mesh.export(file_type="glb")


def glb_sha256(result: PipelineResult) -> str:
    return hashlib.sha256(glb_bytes(result)).hexdigest()
